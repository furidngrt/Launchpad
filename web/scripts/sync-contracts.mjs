// Copies the ABIs the interface needs, and a deployment's addresses, into a
// generated module. The output is committed, so a hosted build never needs
// the Solidity toolchain.
//
//   npm run build            # at the repository root, so ../out exists
//   NETWORK=sepolia npm run sync
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, "..", "..");
const network = process.env.NETWORK ?? "sepolia";

const EXPLORERS = { sepolia: "https://sepolia.etherscan.io" };
const CONTRACTS = [
  "LaunchFactory",
  "BondingCurve",
  "LaunchToken",
  "LaunchLens",
  "LaunchRouter",
  "FeeEscrow",
  "FeeCollector",
  "AmmV3Venue",
  "LiquidityLocker",
];

const deployment = JSON.parse(fs.readFileSync(path.join(root, "deployments", `${network}.json`), "utf8"));
const abis = {};
for (const name of CONTRACTS) {
  const file = path.join(root, "out", `${name}.json`);
  if (!fs.existsSync(file)) throw new Error(`missing ${file}; run "npm run build" at the repository root first`);
  abis[name] = JSON.parse(fs.readFileSync(file, "utf8")).abi;
}

const startBlock = Math.min(...Object.values(deployment.contracts).map((c) => c.block));
const addresses = Object.fromEntries(Object.entries(deployment.contracts).map(([k, v]) => [k, v.address]));

const out = `// Generated by scripts/sync-contracts.mjs from deployments/${network}.json. Do not edit.
import type { Abi, Address } from "viem";

export const deployment = {
  network: ${JSON.stringify(network)},
  chainId: ${deployment.chainId},
  startBlock: ${startBlock}n,
  explorer: ${JSON.stringify(EXPLORERS[network] ?? "")},
  positionManager: ${JSON.stringify(deployment.positionManager)} as Address,
  wrappedNative: ${JSON.stringify(deployment.wrappedNative)} as Address,
  contracts: ${JSON.stringify(addresses, null, 2).replace(/"(0x[0-9a-fA-F]{40})"/g, '"$1" as Address')},
  configs: ${JSON.stringify(deployment.configs.map((c) => ({ id: c.id, label: c.label })))},
} as const;

export const abis = {
${CONTRACTS.map((name) => `  ${name}: ${JSON.stringify(abis[name])} as Abi,`).join("\n")}
};
`;

const target = path.join(here, "..", "src", "generated", "contracts.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(root, target)} for ${network} (${CONTRACTS.length} ABIs)`);
